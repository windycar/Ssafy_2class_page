create table if not exists public.members (
  id bigint generated by default as identity primary key,
  student_id integer unique,
  name text not null check (char_length(name) between 1 and 40),
  username text not null,
  login_id text not null unique check (login_id = lower(login_id)),
  class_name text not null,
  role text not null default 'member' check (role in ('member', 'admin')),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  auth_email text unique,
  is_active boolean not null default true,
  must_change_password boolean not null default true,
  password_changed_at timestamptz,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists members_auth_user_id_idx on public.members (auth_user_id);
create index if not exists members_role_active_idx on public.members (role, is_active);
create index if not exists members_class_name_idx on public.members (class_name);

