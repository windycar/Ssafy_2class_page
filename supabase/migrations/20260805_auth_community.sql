create or replace function public.create_anonymous_post(p_title text, p_content text)
returns public.anonymous_posts
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_member_id bigint;
  v_post public.anonymous_posts;
begin
  if v_user_id is null then
    raise exception 'authentication required';
  end if;

  select id into v_member_id
  from public.members
  where auth_user_id = v_user_id and is_active = true;

  if v_member_id is null then
    raise exception 'active member required';
  end if;
  if char_length(trim(p_title)) < 1 or char_length(trim(p_title)) > 80 then
    raise exception 'title must be between 1 and 80 characters';
  end if;
  if char_length(trim(p_content)) < 1 or char_length(trim(p_content)) > 1000 then
    raise exception 'content must be between 1 and 1000 characters';
  end if;

  insert into public.anonymous_posts (id, title, content, created_at, updated_at)
  values ('post-' || replace(gen_random_uuid()::text, '-', ''), trim(p_title), trim(p_content), now(), now())
  returning * into v_post;

  insert into public.anonymous_post_authors (post_id, auth_user_id, member_id)
  values (v_post.id, v_user_id, v_member_id);

  return v_post;
end;
$$;

revoke all on function public.create_anonymous_post(text, text) from public, anon;
grant execute on function public.create_anonymous_post(text, text) to authenticated;

-- 기존의 광범위한 정책을 제거한 뒤 최소 권한 정책으로 교체합니다.
do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in (
        'members', 'anonymous_posts', 'anonymous_post_authors',
        'coffee_orders', 'coffee_order_items', 'ground_rules', 'ground_rule_likes'
      )
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end;
$$;

