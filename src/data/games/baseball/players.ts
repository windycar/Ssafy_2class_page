export const BASEBALL_PLAYER_BY_ID: Readonly<Record<string, BaseballPlayer>> = Object.freeze(
  Object.assign(
    Object.create(null) as Record<string, BaseballPlayer>,
    Object.fromEntries(ALL_BASEBALL_PLAYERS.map((player) => [player.id, player])),
  ),
);

export function getBaseballPlayer(playerId: string): BaseballPlayer | undefined {
  return Object.hasOwn(BASEBALL_PLAYER_BY_ID, playerId)
    ? BASEBALL_PLAYER_BY_ID[playerId]
    : undefined;
}
